import { HTTP_STATUS, type HttpStatus } from './http.constants.ts';

export const DOMAIN_ERROR_STATUS_MAP: Record<string, HttpStatus> = {
	PLAN_NOT_FOUND: HTTP_STATUS.NOT_FOUND,
	PAYMENT_ORDER_NOT_FOUND: HTTP_STATUS.NOT_FOUND,
	ORDER_PAYMENT_NOT_FOUND: HTTP_STATUS.NOT_FOUND,
	RESOURCE_NOT_FOUND: HTTP_STATUS.NOT_FOUND,
	NOT_FOUND: HTTP_STATUS.NOT_FOUND,
	SUBSCRIBER_NOT_FOUND: HTTP_STATUS.NOT_FOUND,
	TRANSACTION_NOT_FOUND: HTTP_STATUS.NOT_FOUND,
	ACTIVE_SUBSCRIPTION_EXISTS: HTTP_STATUS.CONFLICT,
	PAYMENT_ALREADY_PROCESSED: HTTP_STATUS.CONFLICT,
	INVALID_PAYMENT_STATE_TRANSITION: HTTP_STATUS.CONFLICT,
	CONFLICT: HTTP_STATUS.CONFLICT,
	UNAUTHORIZED_RESTAURANT: HTTP_STATUS.UNAUTHORIZED,
	UNAUTHORIZED: HTTP_STATUS.UNAUTHORIZED,
	CUSTOMER_UNAUTHORIZED: HTTP_STATUS.FORBIDDEN,
	FORBIDDEN: HTTP_STATUS.FORBIDDEN,
	INVALID_PAYMENT_SIGNATURE: HTTP_STATUS.BAD_REQUEST,
	BAD_REQUEST: HTTP_STATUS.BAD_REQUEST,
	PAYMENT_ALREADY_REFUNDED: HTTP_STATUS.CONFLICT,
	CANNOT_REFUND_UNCAPTURED_PAYMENT: HTTP_STATUS.UNPROCESSABLE_ENTITY,
	REFUND_AMOUNT_EXCEEDS_BALANCE: HTTP_STATUS.BAD_REQUEST,
	REFUND_GATEWAY_ERROR: HTTP_STATUS.BAD_GATEWAY,
	GATEWAY_ERROR: HTTP_STATUS.BAD_GATEWAY,
};

export function getStatusCodeForDomainError(
	code: string,
	fallback: HttpStatus = HTTP_STATUS.INTERNAL_SERVER_ERROR,
): HttpStatus {
	return DOMAIN_ERROR_STATUS_MAP[code] || fallback;
}
